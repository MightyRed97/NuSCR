def build_cp(consts):
    mb = ModuleBuilder("CP", "Coincidence Processor",
                       "Receives the trip and bypass status of every trip function from the bistable processors of "
                       "all four channels, performs 2-out-of-4 coincidence logic (2-out-of-3 with one channel "
                       "bypassed) and generates the reactor trip initiation signal.  Each channel has identical "
                       "coincidence processors; one representative instance is specified.", consts)
    for c in CHANNELS:
        for t in TRIPS:
            x = t["id"]
            mb.var(f"f_{c}_{x}_Trip", "input", "trip", f"{t['title']} trip of channel {c} (from BP_{c}).",
                   nominal="1", source=f"BP_{c}.th_{x}_Trip via data link")
            mb.var(f"f_{c}_{x}_Byp", "input", "switch", f"{t['title']} trip channel bypass request of channel {c}.",
                   nominal="0", source=f"BP_{c}.f_{x}_Byp_Sw via data link")
    for c in CHANNELS:
        mb.var(f"f_{c}_Link_Error", "input", "error_flag", f"Failure of the data link from channel {c}.",
               nominal="0", source="Communication diagnostics")
    for t in TRIPS:
        x = t["id"]
        g = mb.group(f"g_{x}_Coincidence", f"{t['title']} coincidence",
                     f"2-out-of-4 coincidence of the {t['title']} trip with trip channel bypass and bypass interlock.",
                     traces=["SYS-CP-01", "SYS-CP-02", "SYS-CP-03"])
        cnt = f"f_{x}_Byp_Cnt"
        mb.var(cnt, "function", "count_0_4", f"Number of channels requesting bypass of the {t['title']} trip.")
        g.sdt(cnt, "Number of channels requesting a trip channel bypass of this function.", ["SYS-CP-02"],
              [], [("", " + ".join(f"f_{c}_{x}_Byp" for c in CHANNELS))])
        for c in CHANNELS:
            v = f"f_{x}_Vote_{c}"
            mb.var(v, "function", "vote", f"Channel {c} vote for the {t['title']} coincidence.")
            g.sdt(v, f"Channel {c} votes to trip when it is tripped or its data link has failed, unless it is the "
                  f"single channel bypassed for this function (a bypass is honoured only when exactly one channel "
                  f"requests it).", ["SYS-CP-01", "SYS-CP-02", "SYS-CP-03"],
                  [f"f_{c}_{x}_Byp = 1 && {cnt} = 1", f"f_{c}_{x}_Trip = 0 || f_{c}_Link_Error = 1"],
                  [("T-", "0"), ("FT", "1"), ("FF", "0")])
        vc = f"f_{x}_Vote_Cnt"
        mb.var(vc, "function", "count_0_4", f"Number of channel votes for the {t['title']} coincidence.")
        g.sdt(vc, "Number of channels voting to trip.", ["SYS-CP-01"], [],
              [("", " + ".join(f"f_{x}_Vote_{c}" for c in CHANNELS))])
        co = f"f_{x}_Coinc"
        mb.var(co, "function", "trip", f"{t['title']} coincidence trip (0 = TRIP).")
        g.sdt(co, "Coincidence trip (0) when two or more channels vote to trip.", ["SYS-CP-01", "SYS-CP-02"],
              [f"{vc} >= 2"], [("T", "0"), ("F", "1")])
        mb.outputs.append(co)
    g = mb.group("g_Trip_Initiation", "Reactor trip initiation",
                 "Reactor trip initiation from any coincidence trip.", traces=["SYS-CP-04"])
    mb.var("f_RT_Init", "function", "trip", "Reactor trip initiation (0 = initiate reactor trip).")
    g.sdt("f_RT_Init", "Initiate a reactor trip (0) when any trip function's coincidence is present.", ["SYS-CP-04"],
          [" || ".join(f"f_{t['id']}_Coinc = 0" for t in TRIPS)], [("T", "0"), ("F", "1")])
    mb.outputs.append("f_RT_Init")
    return mb


def build_system():
    instances = [{"name": f"BP_{c}", "module": "BP", "channel": c} for c in CHANNELS]
    instances.append({"name": "CP_A", "module": "CP", "channel": "A",
                      "note": "Representative coincidence processor; those of channels B-D are identical."})
    connections = []
    for c in CHANNELS:
        for t in TRIPS:
            x = t["id"]
            connections.append({"to": f"CP_A.f_{c}_{x}_Trip", "from": f"BP_{c}.th_{x}_Trip"})
            connections.append({"to": f"CP_A.f_{c}_{x}_Byp", "from": f"BP_{c}.f_{x}_Byp_Sw"})
    return {"description": "Four redundant channels A-D, each with a bistable processor; every coincidence "
                           "processor receives the bistable outputs of all four channels.  Links are modelled as "
                           "ideal (same-scan) transfers; link failure is modelled by the CP inputs `f_<ch>_Link_Error`.",
            "instances": instances, "evaluation_order": [i["name"] for i in instances],
            "connections": connections}


