class ModuleBuilder:
    def __init__(self, name, title, description, constants):
        self.name, self.title, self.description = name, title, description
        self.constants = constants
        self.variables = {}
        self.definitions = {}
        self.groups = []
        self.outputs = []
        self.obligations = []

    def var(self, name, cls, type_, description, unit=None, **extra):
        if name in self.variables:
            raise ValueError(f"{self.name}: duplicate variable {name}")
        d = {"name": name, "class": cls, "type": type_}
        if unit:
            d["unit"] = unit
        d["description"] = description
        d.update({k: v for k, v in extra.items() if v is not None})
        self.variables[name] = d

    def group(self, name, title, description, logic_type=None, category=None, traces=()):
        g = GroupBuilder(self, str(len(self.groups) + 1), name, title, description, logic_type, category, traces)
        self.groups.append(g)
        return g

    def obligation(self, oid, formula, rationale):
        parse(formula, "bool")
        self.obligations.append({"id": oid, "formula": formula, "rationale": rationale})

    def node_inputs(self, var):
        d = self.definitions[var]
        texts = []
        if d["type"] == "SDT":
            texts += d["conditions"] + d["actions"]
        else:
            texts.append(d["initial_value"])
            for t in d["transitions"]:
                texts += [t["guard"], t["action"]]
                if t.get("timing"):
                    texts += [t["timing"]["lower"], t["timing"]["upper"]]
            texts += [m["when"] for m in d.get("must_exit", [])]
            texts += [f["when"] for f in d.get("forced_value", [])]
        refs = set()
        for t in texts:
            refs |= variables(parse(t))
        return sorted(r for r in refs if r != var and r not in self.constants)

    def to_json(self):
        nodes = []
        for g in self.groups:
            nodes.append({
                "no": g.no, "name": g.name, "type": "group", "title": g.title,
                **({"logic_type": g.logic_type} if g.logic_type else {}),
                **({"category": g.category} if g.category else {}),
                "description": g.description, "traces": list(g.traces),
                "nodes": [{"no": no, "name": var, "type": kind, "inputs": self.node_inputs(var)}
                          for no, var, kind in g.nodes],
            })
        return {
            "name": self.name, "title": self.title, "description": self.description,
            "variables": list(self.variables.values()),
            "outputs": self.outputs,
            "fod": {"name": f"g_{self.name}", "title": self.title, "nodes": nodes},
            "definitions": self.definitions,
            "execution_order": [],
            "obligations": self.obligations,
        }


class GroupBuilder:
    def __init__(self, mb, no, name, title, description, logic_type, category, traces):
        self.mb, self.no, self.name, self.title = mb, no, name, title
        self.description, self.logic_type, self.category, self.traces = description, logic_type, category, traces
        self.nodes = []

    def _add(self, var, definition):
        if var in self.mb.definitions:
            raise ValueError(f"{var} defined twice")
        no = f"{self.no}.{len(self.nodes) + 1}"
        self.nodes.append((no, var, definition["type"]))
        self.mb.definitions[var] = definition

    def sdt(self, var, description, traces, conditions, rules):
        """rules: [(cells, action_text)] with cells a string over T/F/-."""
        actions, out = [], []
        for cells, act in rules:
            if act not in actions:
                actions.append(act)
            out.append({"cells": list(cells), "action": actions.index(act)})
        self._add(var, {"type": "SDT", "description": description, "traces": list(traces),
                        "conditions": list(conditions), "actions": actions, "rules": out})

    def machine(self, kind, var, description, traces, states, initial_state, initial_value, transitions,
                must_exit=(), forced_value=()):
        """states: [(name, value|None)];  transitions: [(id, src, dst, guard, action[, (lower, upper)])];
        must_exit: [(state, condition)] - the checker proves that `state` is left whenever `condition` holds;
        forced_value: [(condition, value)] - the checker proves that whenever `condition` holds the variable has
        `value` after the scan, from every state."""
        trans = []
        for t in transitions:
            tr = {"id": t[0], "from": t[1], "to": t[2], "guard": t[3], "action": t[4]}
            if len(t) > 5:
                tr["timing"] = {"lower": t[5][0], "upper": t[5][1]}
            trans.append(tr)
        d = {"type": kind, "description": description, "traces": list(traces),
             "states": [{"name": n, **({"value": v} if v is not None else {})} for n, v in states],
             "initial_state": initial_state, "initial_value": initial_value,
             "transitions": trans}
        if must_exit:
            d["must_exit"] = [{"state": s, "when": w} for s, w in must_exit]
        if forced_value:
            d["forced_value"] = [{"when": w, "value": v} for w, v in forced_value]
        self._add(var, d)


