"""Renders the function-block design (2_design/rps_design.json) as a Software Design Specification with
Mermaid diagrams, plus CSV tables.

    python -B tools/render_design.py

Outputs:  2_design/RPS_Software_Design.md, 2_design/tables/instances.csv, 2_design/tables/trace_nuscr_to_design.csv
"""
from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from design_model import check_design, load_design                    # noqa: E402
from nuscr_lang import format_number                                  # noqa: E402
from nuscr_model import fod_key                                      # noqa: E402
from paths import DESIGN_DIR, DESIGN_REPORT, DESIGN_TABLES            # noqa: E402
from render_docs import anchor, cell, code, table                    # noqa: E402


def prose(text):
    """Table-safe prose: placeholders such as <X> are shown literally and underscores do not start emphasis."""
    return cell(text).replace("<", "&lt;").replace("_", "\\_")


def st_lines(stmts):
    """Render a single-assignment block body as Structured-Text-like lines."""
    out = []
    for st in stmts:
        v = st["set"]
        if "expr" in st:
            out.append(f"{v} := {st['expr']};")
        else:
            for k, (guard, expr) in enumerate(st["cases"]):
                out.append(f"{'IF' if k == 0 else 'ELSIF'} {guard} THEN {v} := {expr};")
            out.append(f"ELSE {v} := {st['else']};")
            out.append("END_IF;")
    return out


def plural(n, word):
    return f"{n} {word}{'' if n == 1 else 's'}"


class DesignRenderer:
    def __init__(self, design, report, findings):
        self.d, self.raw, self.report, self.findings = design, design.raw, report, findings
        self.lines = []

    def w(self, *parts):
        self.lines.extend(parts)

    def render(self):
        doc = self.raw["document"]
        self.w(f"# {doc['title']}", "",
               f"> **STATUS: {doc['status']}**", ">",
               "> The design inherits every ILLUSTRATIVE placeholder constant of the requirements specification.",
               "",
               table(["Field", "Value"], [["Document ID", doc["id"]], ["Revision", doc["revision"]],
                                          ["Date", doc["date"]],
                                          ["Implements", f"{doc['implements']['id']} (`{doc['implements']['file']}`)"],
                                          ["Machine-readable source", "`2_design/rps_design.json` (rps-design-json/2.0)"],
                                          ["Generated by", "`tools/render_design.py` - do not edit by hand"]]), "")
        sections = ["Scope", "Recommended design tool", "Design conventions and decisions", "Data types",
                    "Architecture", "Function block library"]
        sections += [f"Module {m['name']} - {m['title']}" for m in self.raw["modules"]]
        sections += ["Traceability", "Verification", "Open items for the implementation phase"]
        self.num = {s: i for i, s in enumerate(sections, 1)}
        self.w("## Contents", "")
        for i, s in enumerate(sections, 1):
            self.w(f"- [{i}. {s}](#{anchor(f'{i}. {s}')})")
        self.w("")
        self.w(f"## {self.num['Scope']}. Scope", "", doc["scope"], "",
               "The design refines the NuSCR requirements into reusable function blocks with explicit state.  "
               "Every design signal carries the name of the NuSCR variable it implements.  Every instance is "
               "proved equivalent to the NuSCR definition it implements (section "
               f"{self.num['Verification']}).", "")
        self.tool_section()
        self.w(f"## {self.num['Design conventions and decisions']}. Design conventions and decisions", "")
        self.w(*[f"- {c}" for c in self.raw["conventions"]])
        self.w("")
        self.types_section()
        self.architecture()
        self.blocks_section()
        for m in self.raw["modules"]:
            self.module_section(self.num[f"Module {m['name']} - {m['title']}"], m)
        self.trace_section()
        self.verification_section()
        n = self.num["Open items for the implementation phase"]
        self.w(f"## {n}. Open items for the implementation phase", "")
        self.w(*[f"- {o}" for o in self.raw["open_items"]])
        self.w("")
        return "\n".join(self.lines) + "\n"

    def tool_section(self):
        t = self.raw["target_tool"]
        self.w(f"## {self.num['Recommended design tool']}. Recommended design tool", "", f"**{t['recommended']}**",
               "", "Rationale:", "")
        self.w(*[f"- {r}" for r in t["rationale"]])
        self.w("", "Conditions:", "")
        self.w(*[f"- {r}" for r in t["conditions"]])
        self.w("", "Alternatives:", "")
        self.w(*[f"- {r}" for r in t["alternatives"]])
        self.w("", "Mapping of design constructs:", "",
               table(["This design", "SCADE Suite (Scade 6)", "IEC 61131-3"],
                     [[cell(a), cell(b), cell(c)] for a, b, c in t["mapping"]]), "")

    def types_section(self):
        self.w(f"## {self.num['Data types']}. Data types", "",
               "In the block bodies, flags are written as 1/0 (`X = 1` means X is TRUE).", "",
               table(["Type", "SCADE", "IEC 61131-3", "Meaning"],
                     [[code(n), code(t["scade"]), code(t["iec"]), cell(t["meaning"])]
                      for n, t in self.raw["types"].items()]), "")

    def architecture(self):
        n_vote = sum(i["block"] == "FB_VOTE_2OO4" for m in self.raw["modules"] if m["name"] == "CP"
                     for i in m["instances"])
        self.w(f"## {self.num['Architecture']}. Architecture", "",
               "Each channel runs the BP design; every CP receives the BP outputs of all four channels.  Within "
               "the BP the data flow is layered:", "",
               "```mermaid", "flowchart LR",
               '  IN(["Process inputs,<br/>CPC signals,<br/>diagnostics,<br/>operator module"]) --> VAL["Input validation<br/>FB_RANGE_CHECK"]',
               '  VAL --> PERM["Permissives<br/>FB_PERMISSIVE_*"]',
               '  IN --> EDGE["Edge detectors<br/>FB_EDGE"]',
               '  PERM --> OB["Operating bypass<br/>FB_OPERATING_BYPASS"]',
               '  EDGE --> OB',
               '  VAL --> SP["Variable setpoints<br/>FB_LIMIT, FB_SP_*"]',
               '  EDGE --> SP',
               '  VAL --> BI["Trip / pre-trip bistables<br/>FB_TRIP_BISTABLE"]',
               '  OB --> BI',
               '  SP --> BI',
               '  BI -->|"th_*_Trip"| OUT(["To every CP"])',
               '  IN -->|"f_*_Byp_Sw (pass-through)"| OUT',
               f'  OUT --> CP["CP: FB_VOTE_2OO4 x {n_vote}<br/>FB_INITIATION"]',
               '  CP --> RT(["Reactor trip<br/>initiation f_RT_Init"])',
               "```", "")

    def blocks_section(self):
        n = self.num["Function block library"]
        self.w(f"## {n}. Function block library", "",
               "Body notation (single assignment): every output, state variable and local is assigned exactly "
               "once per scan, in statement order.  `last_S` is the value of state variable S at the end of the "
               "previous scan; S read after its assignment is the current value.  `=` is equality, `&&` `||` `!` "
               "are logic operators.", "")
        usage = {}
        for m in self.raw["modules"]:
            for i in m["instances"]:
                usage.setdefault(i["block"], []).append(i["name"])
        for k, (name, b) in enumerate(self.raw["blocks"].items(), 1):
            self.w(f"### {n}.{k} `{name}`", "", prose(b["description"]), "",
                   f"Implements the NuSCR {prose(b['realizes'])}.  Used by "
                   f"{plural(len(usage.get(name, [])), 'instance')}.", "")
            rows = [["input", code(p["name"]), code(p["type"]), prose(p["description"])] for p in b["inputs"]]
            rows += [["parameter", code(p["name"]), code(p["type"]), prose(p["description"])] for p in b["params"]]
            rows += [["state", code(p["name"]), code(p["type"]),
                      prose(p["description"]) + f" Initial value `{p['init']}`."] for p in b["state"]]
            rows += [["local", code(p["name"]), code(p["type"]), prose(p["description"])] for p in b["locals"]]
            rows += [["output", code(p["name"]), code(p["type"]), prose(p["description"])] for p in b["outputs"]]
            self.w(table(["Kind", "Name", "Type", "Description"], rows), "", "```text", *st_lines(b["body"]),
                   "```", "")

    def module_section(self, n, m):
        insts = m["instances"]
        self.w(f"## {n}. Module {m['name']} - {m['title']}", "", cell(m["description"]), "")
        if m.get("interface"):
            self.w(f"Interface: {prose(m['interface'])}", "")
        groups = []
        for i in insts:
            if i.get("group", "") not in groups:
                groups.append(i.get("group", ""))
        consts = self.d.spec.constants
        k = 0
        for g in groups:
            k += 1
            self.w(f"### {n}.{k} `{g}`", "")
            rows = []
            for i in (x for x in insts if x.get("group", "") == g):
                params = []
                for p, v in i["params"].items():
                    val = self.d.instance(m["name"], i["name"]).params[p]
                    params.append(f"{code(p)} = {code(v)}" + (f" = {format_number(val)}" if p == "DELAY" else ""))
                ins = "<br/>".join(f"{code(p)} = {code(v)}" for p, v in i["inputs"].items())
                outs = "<br/>".join(f"{code(p)} -> {code(v)}" for p, v in i["outputs"].items())
                rows.append([code(i["name"]), code(i["block"]), "<br/>".join(params), ins, outs])
            self.w(table(["Instance", "Block", "Parameters", "Inputs", "Outputs"], rows), "")
        order = self.d.order[m["name"]]
        self.w(f"### {n}.{k + 1} Execution order", "",
               "<details><summary>Show all " + str(len(order)) + " instances</summary>", "")
        self.w(*[f"{j + 1}. `{inst.name}` ({inst.block.name})" for j, inst in enumerate(order)])
        self.w("", "</details>", "")

    def trace_section(self):
        n = self.num["Traceability"]
        self.w(f"## {n}. Traceability", "",
               "NuSCR definition (FOD node) to the design instance that implements it and is proved equivalent to "
               "it.  Requirement-level traceability follows through the requirements specification.", "")
        spec = self.d.spec
        for k, m in enumerate(self.raw["modules"], 1):
            req = spec.modules[m["name"]]
            impl = {}
            for i in m["instances"]:
                for v in i["implements"]:
                    impl.setdefault(v, []).append(i["name"])
            rows = [[f"{m['name']}.{req.nodes[v].no}", code(v), req.definitions[v].kind,
                     ", ".join(code(x) for x in impl.get(v, [])) or "*(none)*"]
                    for v in sorted(req.definitions, key=lambda v: fod_key(req.nodes[v].no))]
            self.w(f"### {n}.{k} Module {m['name']}", "",
                   table(["FOD node", "NuSCR variable", "Kind", "Design instance"], rows), "")

    def verification_section(self):
        n = self.num["Verification"]
        rep = self.report
        pc, tc = rep["proof_coverage"], rep["transition_coverage"]
        methods = {}
        for r in rep["instance_proofs"]:
            methods.setdefault(r["method"], [0, 0])
            methods[r["method"]][0] += 1
            methods[r["method"]][1] += r["passed"]
        descr = {"pattern": "transition guards equal the pattern guards with the instance bindings substituted "
                            "(decision procedure); states, targets, actions and delay identical",
                 "symbolic": "block output evaluated symbolically equals the SDT value for every input",
                 "refinement": "inductive refinement proof, requirement state and value versus block state",
                 "exhaustive": "all input combinations of the instance enumerated"}
        self.w(f"## {n}. Verification", "",
               f"Static design check (`tools/design_model.py`): "
               f"{sum(1 for f in self.findings if f[0] == 'ERROR')} error(s).  It includes the exact wiring check: "
               "every instance reads exactly the NuSCR variables, and uses exactly the constants, that the "
               "definitions it implements use.", "",
               f"### {n}.1 Proofs (`tools/design_verify.py`)", "",
               "Block equivalence, by exhaustive exploration of every reachable pair of (requirements state, block "
               "state) for every input combination:", "",
               table(["Check", "Size", "Result"],
                     [[cell(r["check"]), r["size"], "pass" if r["passed"] else "**FAIL**"]
                      for r in rep["block_equivalence"]]), "",
               "Instance proofs, one per instance:", "",
               table(["Method", "Instances", "Proved", "What is shown"],
                     [[m, c[0], c[1], descr.get(m, "")] for m, c in sorted(methods.items())]), "",
               f"NuSCR definitions covered by a proved instance: {pc['proved']} of {pc['definitions']}.  Pattern "
               "proofs rely on the block-equivalence results above.  The instance proofs compose into module "
               "equivalence because every signal carries the name of the NuSCR variable it implements and the "
               "static check fixes each instance's inputs.  The per-instance results are listed in "
               "`6_verification/design_verification_report.json`.", "",
               f"### {n}.2 Back-to-back tests", "",
               "Additional evidence: the design and the requirements model are simulated side by side and every "
               "computed signal is compared in every scan.  The BP stimuli include values placed relative to the "
               "moving setpoints.", "",
               table(["Test", "Size", "Result"],
                     [[cell(r["check"]), r["size"], "pass" if r["passed"] else "**FAIL**"]
                      for r in rep["back_to_back"]]), "",
               f"Transition coverage of the requirements model in the BP runs: {tc['fired']} of {tc['transitions']}.",
               "",
               "These results show that the design implements this synthetic requirements specification exactly.  "
               "They are not independent V&V and do not establish fitness for any real plant.", "")


def write_csvs(design):
    DESIGN_TABLES.mkdir(parents=True, exist_ok=True)
    with open(DESIGN_TABLES / "instances.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["module", "instance", "block", "group", "parameters", "inputs", "outputs", "implements"])
        for m in design.raw["modules"]:
            for i in m["instances"]:
                w.writerow([m["name"], i["name"], i["block"], i.get("group", ""),
                            "; ".join(f"{p}={v}" for p, v in i["params"].items()),
                            "; ".join(f"{p}={v}" for p, v in i["inputs"].items()),
                            "; ".join(f"{p}->{v}" for p, v in i["outputs"].items()),
                            " ".join(i["implements"])])
    with open(DESIGN_TABLES / "trace_nuscr_to_design.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["module", "nuscr_variable", "fod_node", "design_instance", "block"])
        for m in design.raw["modules"]:
            req = design.spec.modules[m["name"]]
            for i in m["instances"]:
                for v in i["implements"]:
                    w.writerow([m["name"], v, req.nodes[v].no, i["name"], i["block"]])


def main():
    design = load_design()
    findings = check_design(design)
    if not DESIGN_REPORT.exists():
        print(f"missing {DESIGN_REPORT}; run tools/design_verify.py first")
        return 1
    report = json.loads(DESIGN_REPORT.read_text(encoding="utf-8"))
    r = DesignRenderer(design, report, findings)
    text = r.render()
    (DESIGN_DIR / "RPS_Software_Design.md").write_text(text, encoding="utf-8", newline="\n")
    write_csvs(design)
    print(f"wrote {DESIGN_DIR / 'RPS_Software_Design.md'} ({text.count(chr(10))} lines), tables/instances.csv, "
          "tables/trace_nuscr_to_design.csv")
    return 1 if any(f[0] == "ERROR" for f in findings) or not report["passed"] else 0


if __name__ == "__main__":
    sys.exit(main())
