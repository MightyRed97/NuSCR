def build():
    consts = build_constants()
    const_names = {c["name"] for c in consts}
    bp, cp = build_bp(const_names), build_cp(const_names)
    raw = {
        "format": FORMAT,
        "document": DOCUMENT,
        "semantics": SEMANTICS,
        "conventions": CONVENTIONS,
        "types": TYPES,
        "constants": consts,
        "assertions": build_assertions(),
        "requirements": build_requirements(),
        "modules": [bp.to_json(), cp.to_json()],
        "system": build_system(),
    }
    spec = Spec(raw)                                  # structural validation
    for m in raw["modules"]:
        order, cycle = topological_order(spec.modules[m["name"]])
        if cycle:
            raise SystemExit(f"data-flow cycle in {m['name']}: {cycle}")
        m["execution_order"] = order
    return raw


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("-o", "--output", default=str(ROOT / "spec" / "rps_nuscr_spec.json"))
    args = ap.parse_args()
    raw = build()
    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(raw, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    n_defs = sum(len(m["definitions"]) for m in raw["modules"])
    print(f"wrote {out} ({len(raw['constants'])} constants, {n_defs} definitions, "
          f"{len(raw['requirements'])} requirements)")


if __name__ == "__main__":
    main()
