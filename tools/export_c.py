def _var_comment(v, extra=""):
    text = v["description"]
    if v.get("unit"):
        text += f" [{v['unit']}]"
    if extra:
        text += f" {extra}"
    return text


def module_files(design, mname, derived):
    spec = design.spec
    req = spec.modules[mname]
    raw_mod = next(m for m in design.raw["modules"] if m["name"] == mname)
    vtype = {n: signal_type(spec.types, v["type"]) for n, v in req.variables.items()}
    signals = design_signals(design, mname)
    outputs = set(module_outputs(design, mname))
    names = {n: f"in->{n}" for n in req.inputs}
    names.update({s: f"out->{s}" for s in signals})
    types = dict(vtype)
    types.update({k: "float64" for k in spec.constants})
    tr = CTranslator(types, consts=spec.constants, derived=derived, names=names)
    lo = mname.lower()
    stateful = [i for i in design.order[mname] if i.block.state]
    producer = {sig: inst for inst in design.order[mname] for sig in inst.outputs.values()}

    h = comment(f"{raw_mod['title']} ({mname}): {raw_mod['description']}")
    h += ["", *comment(f"Inputs of the {raw_mod['title'].lower()}: the NuSCR {mname} inputs."), "typedef struct {"]
    for n in req.inputs:
        h += comment(_var_comment(req.variables[n]), "    ")
        h.append(f"    {C_TYPE[vtype[n]]} {n};")
    h += [f"}} RPS_{mname}_Inputs;", ""]
    h += comment("Every signal the design computes, in execution order, named after the NuSCR variable it "
                 "implements.  Flags: 1 = TRUE; trip, pre-trip and coincidence signals are 1 = NORMAL, 0 = TRIP.")
    h.append("typedef struct {")
    for s in signals:
        inst = producer[s]
        where = f"({inst.name}, {inst.block.name}{', module output' if s in outputs else ''})"
        h += comment(_var_comment(req.variables[s], where), "    ")
        if vtype[s] != value_type(inst.block.raw["outputs"][0]["type"]):
            raise ExportError(f"{mname}.{inst.name}: signal {s} and block output have different types")
        h.append(f"    {C_TYPE[vtype[s]]} {s};")
    h += [f"}} RPS_{mname}_Signals;", ""]
    h += comment("State of every stateful block instance.") + ["typedef struct {"]
    if stateful:
        h += [f"    {i.block.name}_State {i.name};" for i in stateful]
    else:
        h.append(f"    int no_state;  /* the {mname} design has no stateful block */")
    h += [f"}} RPS_{mname}_State;", ""]
    h += comment("Power-up: every block instance in its initial state.")
    h += [f"void RPS_{mname}_init(RPS_{mname}_State *st);", ""]
    h += comment("The nominal value of every input.")
    h += [f"void RPS_{mname}_nominal_inputs(RPS_{mname}_Inputs *in);", ""]
    h += comment("One scan: reads the inputs, executes every block instance once in the design's execution order "
                 "and writes every computed signal.")
    h += [f"void RPS_{mname}_step(RPS_{mname}_State *st, const RPS_{mname}_Inputs *in, RPS_{mname}_Signals *out);",
          ""]

    c = [f"void RPS_{mname}_init(RPS_{mname}_State *st)", "{"]
    c += [f"    {i.block.name}_init(&st->{i.name});" for i in stateful] or ["    st->no_state = 0;"]
    c += ["}", "", f"void RPS_{mname}_nominal_inputs(RPS_{mname}_Inputs *in)", "{"]
    for n in req.inputs:
        c.append(f"    in->{n} = {literal(to_fraction(req.variables[n]['nominal']), vtype[n])};")
    c += ["}", "", f"void RPS_{mname}_step(RPS_{mname}_State *st, const RPS_{mname}_Inputs *in, "
                   f"RPS_{mname}_Signals *out)", "{"]
    if not stateful:
        c.append("    (void)st;")
    group = None
    for inst in design.order[mname]:
        b = inst.block.raw
        if inst.raw.get("group") != group:
            group = inst.raw.get("group")
            c += (["", f"    /* ---- {group} ---- */"] if group else [""])
        args = [(p["name"], tr.value(inst.binding_asts[p["name"]], value_type(p["type"]))) for p in b["inputs"]]
        for p in b["params"]:
            if p["name"] == "DELAY":
                args.append(("DELAY", delay_const(inst)))
            else:
                args.append((p["name"], tr.value(parse(inst.raw["params"][p["name"]]), value_type(p["type"]))))
        if inst.block.state:
            args.insert(0, ("", f"&st->{inst.name}"))
        (_, sig), = inst.outputs.items()
        c += comment(f"{inst.name} ({inst.block.name}) implements {', '.join(inst.raw['implements'])}", "    ")
        c += call(f"out->{sig}", inst.block.name, args, inst.name)
    c += ["}", ""]
    purpose = f"{raw_mod['title'].lower()} ({mname}), one scan per call."
    return {f"rps_{lo}.h": header(design, f"rps_{lo}", purpose, ['"rps_blocks.h"'], h),
            f"rps_{lo}.c": source(design, f"rps_{lo}", purpose, [f'"rps_{lo}.h"', '"rps_constants.h"'], c)}


