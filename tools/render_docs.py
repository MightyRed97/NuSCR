def write_csvs(spec, renderer, out_dir: Path):
    out_dir.mkdir(parents=True, exist_ok=True)

    def dump(name, header, rows):
        with open(out_dir / name, "w", newline="", encoding="utf-8") as f:
            w = csv.writer(f, lineterminator="\n")
            w.writerow(header)
            w.writerows(rows)

    raw = spec.raw
    dump("constants.csv", ["name", "value", "expr", "evaluated", "unit", "category", "status", "description"],
         [[c["name"], c.get("value", ""), c.get("expr", ""), format_number(spec.constants[c["name"]]),
           c.get("unit", ""), c.get("category", ""), c["status"], c["description"]] for c in raw["constants"]])
    dump("requirements.csv", ["id", "category", "text"],
         [[r["id"], r["category"], r["text"]] for r in raw["requirements"]])
    rows, fod, sdt_c, sdt_r, states, trans = [], [], [], [], [], []
    for m in spec.modules.values():
        pos = {v: i + 1 for i, v in enumerate(m.execution_order)}
        for n, v in m.variables.items():
            node = m.nodes.get(n)
            rows.append([m.name, n, v["class"], v["type"], v.get("unit", ""),
                         " .. ".join(v["range"]) if "range" in v else "", v.get("nominal", ""),
                         v.get("source", ""), node.no if node else "", node.group if node else "", v["description"]])
        for var in sorted(m.definitions, key=lambda x: fod_key(m.nodes[x].no)):
            d, node = m.definitions[var], m.nodes[var]
            fod.append([m.name, node.no, node.group, var, d.kind, " ".join(sorted(m.data_inputs(var))), pos[var],
                        " ".join(d.raw.get("traces", []))])
            if d.kind == "SDT":
                for i, (text, _) in enumerate(d.conditions, 1):
                    sdt_c.append([m.name, var, i, text])
                for r in d.rules:
                    sdt_r.append([m.name, var, r.index, " ".join(r.cells), d.actions[r.action][0]])
            else:
                for s in d.states:
                    sv = d.state_values[s]
                    states.append([m.name, var, d.kind, s, sv[0] if sv else "",
                                   "yes" if s == d.initial_state else ""])
                for t in d.transitions:
                    trans.append([m.name, var, d.kind, t.id, t.source, t.target, t.lower_text or "",
                                  t.upper_text or "", t.guard_text, t.action_text])
    dump("variables.csv", ["module", "name", "class", "type", "unit", "range", "nominal", "source", "fod_node",
                           "group", "description"], rows)
    dump("fod_nodes.csv", ["module", "fod_node", "group", "variable", "kind", "inputs", "execution_index",
                           "traces"], fod)
    dump("sdt_conditions.csv", ["module", "variable", "condition_no", "condition"], sdt_c)
    dump("sdt_rules.csv", ["module", "variable", "rule", "cells", "action"], sdt_r)
    dump("machine_states.csv", ["module", "variable", "kind", "state", "value", "initial"], states)
    dump("transitions.csv", ["module", "variable", "kind", "id", "from", "to", "timing_lower", "timing_upper",
                             "guard", "action"], trans)
    dump("connections.csv", ["to", "from"], [[c["to"], c["from"]] for c in raw["system"]["connections"]])
    ob_rows = []
    for m in spec.modules.values():
        ob_rows += [[m.name, ob["id"], "obligation", "", ob["formula"], ob.get("rationale", "")] for ob, _ in m.obligations]
        ob_rows += [[m.name, f"EXIT-{var}-{st}", "must_exit", var, text, f"{st} is left whenever the condition holds"]
                    for var, d in m.definitions.items() for st, text, _ in d.must_exit]
        ob_rows += [[m.name, f"FORCE-{var}", "forced_value", var, w, f"value is {v} after every scan in which the "
                     f"condition holds, from every state"]
                    for var, d in m.definitions.items() for w, _, v, _ in d.forced_value]
    dump("obligations.csv", ["module", "id", "kind", "machine", "formula", "rationale"], ob_rows)
    trace_rows = [[rid, mod, var.split(".", 1)[1], no, ""]
                  for rid, nodes in renderer.trace().items() for mod, var, no in nodes]
    trace_rows += [[r["id"], "", "", "", a] for r in raw["requirements"] for a in r.get("allocated_to", [])]
    dump("traceability.csv", ["requirement", "module", "variable", "fod_node", "allocation"],
         sorted(trace_rows, key=lambda row: [x["id"] for x in raw["requirements"]].index(row[0])))


def main(argv=None):
    ap = argparse.ArgumentParser(description="Render the NuSCR specification as Markdown and CSV.")
    ap.add_argument("spec", nargs="?", default=str(default_spec_path()))
    ap.add_argument("--docs", default=str(ROOT / "docs"))
    ap.add_argument("--data", default=str(ROOT / "data"))
    args = ap.parse_args(argv)
    spec = load(args.spec)
    report = check_spec(spec)
    r = Renderer(spec, report)
    docs = Path(args.docs)
    docs.mkdir(parents=True, exist_ok=True)
    (docs / "NuSCR_RPS_SRS.md").write_text(r.render(), encoding="utf-8", newline="\n")
    (docs / "check_report.json").write_text(json.dumps({
        "errors": len(report.errors), "warnings": len(report.warnings), "stats": dict(report.stats),
        "findings": [f.__dict__ for f in report.findings]}, indent=2) + "\n", encoding="utf-8", newline="\n")
    write_csvs(spec, r, Path(args.data))
    print(f"wrote {docs / 'NuSCR_RPS_SRS.md'} ({len(r.lines)} lines), {docs / 'check_report.json'}, "
          f"CSV tables in {args.data}")
    return 1 if report.errors else 0


if __name__ == "__main__":
    sys.exit(main())
