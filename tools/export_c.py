# Text helpers
# ---------------------------------------------------------------------------

def comment(text, indent=""):
    text = " ".join(str(text).split()).replace("*/", "* /")
    lines = textwrap.wrap(text, WIDTH - len(indent) - 6) or [""]
    if len(lines) == 1:
        return [f"{indent}/* {lines[0]} */"]
    return [f"{indent}/* {lines[0]}"] + [f"{indent} * {line}" for line in lines[1:]] + [f"{indent} */"]


def banner(design, filename, purpose):
    doc = design.raw["document"]
    paragraphs = [f"{filename} - {purpose}",
                  f"Generated by tools/export_c.py from 2_design/rps_design.json ({doc['id']} revision "
                  f"{doc['revision']}).  Do not edit by hand: change the design and regenerate.",
                  f"STATUS: {doc['status']}.  Every constant is an ILLUSTRATIVE placeholder."]
    out = ["/*"]
    for k, para in enumerate(paragraphs):
        if k:
            out.append(" *")
        out += [f" * {line}" for line in textwrap.wrap(para, WIDTH - 3)]
    return out + [" */", ""]


def guard(name):
    return f"RPS_{name.upper()}_H"


def header(design, name, purpose, includes, body):
    g = guard(name)
    return "\n".join(banner(design, f"{name}.h", purpose) + [f"#ifndef {g}", f"#define {g}", ""]
                     + [f"#include {i}" for i in includes] + [""] + body + [f"#endif  /* {g} */", ""])


def source(design, name, purpose, includes, body):
    return "\n".join(banner(design, f"{name}.c", purpose) + [f"#include {i}" for i in includes] + [""] + body)


def call(target, function, args, label, indent="    "):
    """`target = function(args);` on one line, or one argument per line with its port name when that is long."""
    one = f"{indent}{target} = {function}({', '.join(a for _, a in args)});"
    if len(one) <= WIDTH:
        return [one]
    lines = [f"{indent}{target} = {function}("]
    for k, (port, arg) in enumerate(args):
        end = ");" if k == len(args) - 1 else ","
        lines.append(f"{indent}    {arg}{end}" + (f"  /* {port} */" if port else ""))
    return lines


