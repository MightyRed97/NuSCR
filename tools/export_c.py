"""Generates the C implementation of the function-block design (2_design/rps_design.json) in 4_code/src:

  rps_constants.h/.c   the constants the design uses, the delays in scans and the thresholds folded at generation
  rps_blocks.h/.c      the 12 function blocks: a state structure, an init function and a step function each
  rps_bp.h/.c          bistable processor: inputs, signals, state, init, nominal inputs and one scan (step)
  rps_cp.h/.c          coincidence processor, the same
  rps_system.h/.c      the four-channel system: BP_A..BP_D and CP_A with their connections
  rps_meta.h/.c        name, type and offset of every input and signal, for tools such as 4_code/app/rps_sim.c

The code follows the design one to one: one C function per block, one call per instance in the design's execution
order, signals named after the NuSCR variables they implement, and last_S (the previous-scan value of state S) read
before S is updated.  The generated code is C11 with no dynamic memory, no recursion and no loops; analog values
are double, flags bool and counters int32_t.  Threshold expressions made only of constants are evaluated exactly at
generation time and emitted as named constants, as in the SCADE export, so that each threshold is rounded once.
tools/verify_c.py compiles the code and compares it with the requirements model scan by scan.

    python -B tools/export_c.py
"""
from __future__ import annotations

import sys
import textwrap
from fractions import Fraction
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from design_model import load_design                                     # noqa: E402
from export_common import (ExportError, Translator, delay_const,         # noqa: E402
                           design_signals, literal, module_outputs, signal_type, used_constants, value_type)
from nuscr_lang import parse, variables                                  # noqa: E402
from nuscr_sim import to_fraction                                        # noqa: E402
from paths import C_SOURCE_DIR                                           # noqa: E402

C_TYPE = {"bool": "bool", "int32": "int32_t", "float64": "double"}
META_TYPE = {"bool": "RPS_BOOL", "int32": "RPS_INT32", "float64": "RPS_REAL"}
WIDTH = 110


class CTranslator(Translator):
    """Design expressions in C: flags are bool, && || !, == for equality; `names` maps a signal to the structure
    member that holds it (in->x, out->x)."""

    AND, OR = "&&", "||"
    CMP = {"=": "==", "!=": "!=", "<": "<", "<=": "<=", ">": ">", ">=": ">="}

    def __init__(self, types, state=(), consts=None, derived=None, names=None):
        super().__init__(types, state, consts, derived)
        self.names = names or {}

    def last(self, name):
        return f"last_{name}"

    def negate(self, text):
        return f"(!{text})"

    def name(self, name):
        return self.names.get(name, name)


