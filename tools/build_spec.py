def build_trip_group(mb, t):
    x, logic, title = t["id"], t["logic"], t["title"]
    meta = LOGIC[logic]
    s = t.get("signal")
    rising = meta["rising"]
    traces = [f"SYS-{x}-01", "SYS-GEN-02", "SYS-GEN-04", "SYS-GEN-05", "SYS-GEN-06", "SYS-GEN-07"]
    if logic.endswith("_OB"):
        traces.append("SYS-GEN-09")                 # the trip machines implement the bypass inhibition
    has_sp = logic in ("VSRT", "RLVSFT_OB", "MRVSFT_OB")
    has_ob = logic.endswith("_OB")
    group_traces = [f"SYS-{x}-01"] + ([f"SYS-{x}-02"] if has_sp else []) + ([f"SYS-{x}-03"] if has_ob else [])
    g = mb.group(f"g_{x}", f"{title} trip", f"{title} trip ({meta['category'].lower()}, NuSCR logic type "
                 f"{meta['name']}).", logic_type=meta["name"], category=meta["category"], traces=group_traces)

    mb.var(f"th_{x}_Trip", "timed_history", "trip", f"{title} channel trip (0 = TRIP).")
    mb.var(f"th_{x}_Pretrip", "timed_history", "pretrip", f"{title} pre-trip alarm (0 = PRETRIP).")

    # --- operating bypass --------------------------------------------------------
    byp = None
    if has_ob:
        byp = f"h_{x}_OB_Sta"
        ob_traces = [f"SYS-{x}-03", "SYS-GEN-09", "SYS-GEN-04"]
        if logic in ("DT_OB", "RLVSFT_OB"):
            perm = "f_LP_OB_Perm"
        else:
            perm = f"f_{x}_OB_Perm"
            mb.var(perm, "function", "permissive", f"{title} operating-bypass permissive.")
            cmp = f"f_{s} >= k_{x}_OB_Perm" if logic == "FSRT_OB" else f"f_{s} < k_{x}_OB_Perm"
            g.sdt(perm, f"Permissive (1) while f_{s} is valid and {cmp.split(' ', 1)[1]}; not permitted (0) "
                  "otherwise, including when the input is invalid.", ob_traces,
                  [f"f_{s}_Valid = 1", cmp], [("TT", "1"), ("TF", "0"), ("F-", "0")])
        ob_pulse = f"h_{x}_OB_Pulse"
        mb.var(ob_pulse, "history", "pulse", f"One-scan pulse for each actuation of f_{x}_OB_Ini.")
        pulse_machine(g, ob_pulse, f"f_{x}_OB_Ini", ob_traces, "operating-bypass initiation")
        mb.var(byp, "history", "bypass_status", f"{title} operating-bypass status (1 = bypassed).")
        ob_machine(g, x, perm, ob_pulse, ob_traces, title)

    # --- setpoint logic ----------------------------------------------------------
    sp = f"h_{x}_Trip_SP"
    unit = SIGNALS[s]["unit"] if s else None
    rng = [f"k_{x}_SP_Min", f"k_{x}_SP_Max"]
    ok_v = f"f_{s}_Valid = 1" if s else None
    if logic in ("VSRT", "RLVSFT_OB"):
        sp_traces = [f"SYS-{x}-02"]
        tgt = f"f_{x}_SP_Target"
        expr = f"f_{s} + k_{x}_Band" if rising else f"f_{s} - k_{x}_Band"
        mb.var(tgt, "function", "real", f"{title} setpoint target: {expr} clamped to [k_{x}_SP_Min, "
               f"k_{x}_SP_Max].", unit=unit, range=rng)
        g.sdt(tgt, f"Unconstrained setpoint target {expr}, clamped to the setpoint limits.", sp_traces,
              [f"{expr} <= k_{x}_SP_Min", f"{expr} >= k_{x}_SP_Max"],
              [("TF", f"k_{x}_SP_Min"), ("FT", f"k_{x}_SP_Max"), ("FF", expr)])
        step = f"k_{x}_SP_Step"
        mb.var(sp, "history", "real", f"{title} variable trip setpoint.", unit=unit, range=rng)
        if rising:
            desc = (f"Rate-limited rising setpoint: initialised to the target on the first valid scan, follows a "
                    f"decreasing target immediately and rises by at most {step} per scan.  Holds its value while "
                    f"f_{s} is invalid.  Initial value k_{x}_SP_Min (most restrictive).")
            trans = [("T1", "INIT", "TRACKING", ok_v, tgt),
                     ("T2", "TRACKING", "TRACKING", f"{ok_v} && {tgt} <= {sp}", tgt),
                     ("T3", "TRACKING", "TRACKING", f"{ok_v} && {tgt} > {sp} && {tgt} - {sp} <= {step}", tgt),
                     ("T4", "TRACKING", "TRACKING", f"{ok_v} && {tgt} - {sp} > {step}", f"{sp} + {step}")]
            init = f"k_{x}_SP_Min"
        else:
            desc = (f"Rate-limited falling setpoint: initialised to the target on the first valid scan, follows an "
                    f"increasing target immediately and falls by at most {step} per scan.  Holds its value while "
                    f"f_{s} is invalid.  Initial value k_{x}_SP_Max (most restrictive).")
            trans = [("T1", "INIT", "TRACKING", ok_v, tgt),
                     ("T2", "TRACKING", "TRACKING", f"{ok_v} && {tgt} >= {sp}", tgt),
                     ("T3", "TRACKING", "TRACKING", f"{ok_v} && {tgt} < {sp} && {sp} - {tgt} <= {step}", tgt),
                     ("T4", "TRACKING", "TRACKING", f"{ok_v} && {sp} - {tgt} > {step}", f"{sp} - {step}")]
            init = f"k_{x}_SP_Max"
        g.machine("FSM", sp, desc, sp_traces, [("INIT", None), ("TRACKING", None)], "INIT", init, trans)
    elif logic == "MRVSFT_OB":
        sp_traces = [f"SYS-{x}-02"]
        pulse, pb = f"h_{x}_Reset_Pulse", f"f_{x}_SP_Reset"
        mb.var(pulse, "history", "pulse", f"One-scan pulse for each actuation of {pb}.")
        pulse_machine(g, pulse, pb, sp_traces, "setpoint reset")
        d = f"f_{s} - k_{x}_Band"
        lo, hi = f"k_{x}_SP_Min", f"k_{x}_SP_Max"
        mb.var(sp, "history", "real", f"{title} manually reset trip setpoint.", unit=unit, range=rng)
        g.machine("FSM", sp, f"Manually reset falling setpoint: starts at {hi}; rises automatically so that it is "
                  f"never more than k_{x}_Band below f_{s} (up to {hi}); each reset pulse lowers it to {d} (not "
                  f"below {lo}).  Holds its value while f_{s} is invalid.", sp_traces,
                  [("ACTIVE", None)], "ACTIVE", hi,
                  [("T1", "ACTIVE", "ACTIVE", f"{ok_v} && {d} > {sp} && {d} <= {hi}", d),
                   ("T2", "ACTIVE", "ACTIVE", f"{ok_v} && {d} > {hi} && {sp} < {hi}", hi),
                   ("T3", "ACTIVE", "ACTIVE", f"{ok_v} && {pulse} = 1 && {d} < {sp} && {d} >= {lo}", d),
                   ("T4", "ACTIVE", "ACTIVE", f"{ok_v} && {pulse} = 1 && {d} < {lo} && {sp} > {lo}", lo)])

    # --- trip and pre-trip machines ------------------------------------------------
    if logic == "DT_OB":
        err, ok = DIG_ERR, DIG_OK
        cond, ncond = f"f_{x}_Trip_In = 0", f"f_{x}_Trip_In = 1"
        reset, nreset = ncond, cond
        pcond, pncond = f"f_{x}_Pretrip_In = 0", f"f_{x}_Pretrip_In = 1"
        preset, pnreset = pncond, pcond
    else:
        err, ok = analog_err(s), analog_ok(s)
        xs = f"f_{s}"
        if has_sp:
            trip_sp = sp
            pre_sp = f"{sp} - k_{x}_Pretrip_Margin" if rising else f"{sp} + k_{x}_Pretrip_Margin"
        else:
            trip_sp, pre_sp = f"k_{x}_Trip_SP", f"k_{x}_Pretrip_SP"
        cond, ncond, reset, nreset = threshold(xs, trip_sp, f"k_{x}_Trip_Hys", rising)
        pcond, pncond, preset, pnreset = threshold(xs, pre_sp, f"k_{x}_Pretrip_Hys", rising)
    trip_machine(mb, g, x, "Pretrip", err, ok, pcond, pncond, preset, pnreset, byp, ["SYS-GEN-08"] + traces,
                 f"{title} pre-trip")
    trip_machine(mb, g, x, "Trip", err, ok, cond, ncond, reset, nreset, byp, traces, f"{title} trip")


