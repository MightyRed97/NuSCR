"""Renders the NuSCR specification (nuscr-json) as a human-readable SRS document
(Markdown with Mermaid diagrams) and as CSV tables for spreadsheets/tools.

    python tools/render_docs.py [spec.json]

Outputs:  docs/NuSCR_RPS_SRS.md, docs/check_report.json, data/*.csv
"""
from __future__ import annotations

import argparse
import csv
import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from nuscr_check import check_spec                           # noqa: E402
from nuscr_lang import format_number                          # noqa: E402
from nuscr_model import default_spec_path, fod_key, load      # noqa: E402

ROOT = Path(__file__).resolve().parent.parent


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def code(text):
    return f"`{cell(text)}`" if text not in (None, "") else ""


def table(header, rows, align=None):
    out = ["| " + " | ".join(header) + " |",
           "|" + "|".join(align or ["---"] * len(header)) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def anchor(text):
    return "".join(ch for ch in text.lower().replace(" ", "-") if ch.isalnum() or ch in "-_")


class Renderer:
    def __init__(self, spec, report):
        self.spec, self.report = spec, report
        self.raw = spec.raw
        self.lines = []

    def w(self, *parts):
        self.lines.extend(parts)

    # ------------------------------------------------------------------
    def render(self):
        doc = self.raw["document"]
        self.w(f"# {doc['title']}", "",
               f"> **STATUS: {doc['status']}**", ">",
               "> Every constant in this document is an ILLUSTRATIVE placeholder. See section 1.", "",
               table(["Field", "Value"], [["Document ID", doc["id"]], ["Revision", doc["revision"]],
                                          ["Date", doc["date"]],
                                          ["Machine-readable source", "`spec/rps_nuscr_spec.json` (nuscr-json/1.0)"],
                                          ["Generated by", "`tools/render_docs.py` - do not edit by hand"]]), "")
        sections = ["Purpose, provenance and limitations", "NuSCR notation and execution semantics",
                    "System overview", "System requirements", "Constants and setpoints"]
        sections += [f"Module {m.name} - {m.title}" for m in self.spec.modules.values()]
        sections += ["System configuration", "Traceability", "Verification status",
                     "Appendix A - Expression grammar"]
        self.w("## Contents", "")
        for i, s in enumerate(sections, 1):
            num = f"{i}. " if not s.startswith("Appendix") else ""
            self.w(f"- [{num}{s}](#{anchor((num + s))})")
        self.w("")
        self.section_1(doc)
        self.section_2()
        self.section_3()
        self.section_4()
        self.section_5()
        for i, m in enumerate(self.spec.modules.values(), 6):
            self.module_section(i, m)
        n = 6 + len(self.spec.modules)
        self.system_section(n)
        self.trace_section(n + 1)
        self.verification_section(n + 2)
        self.grammar_appendix()
        return "\n".join(self.lines) + "\n"

    def section_1(self, doc):
        self.w("## 1. Purpose, provenance and limitations", "",
               "This document is the NuSCR software requirements specification of a notional four-channel digital "
               "reactor protection system: the bistable processor (BP) logic of each channel and the coincidence "
               "processor (CP) logic.  It exists to provide complete, internally consistent NuSCR design data for "
               "tool development, method research, training and prototyping.", "",
               "**Provenance.** " + doc["provenance"], "", "**Limitations.**", "")
        for lim in doc["limitations"]:
            self.w(f"- {lim}")
        self.w("", "**Applicable standards.**", "")
        for r in doc["references"]:
            self.w(f"- [{r['id']}] {r['text']}" + (f" <{r['url']}>" if r.get("url") else ""))
        self.w("")

    def section_2(self):
        sem, conv = self.raw["semantics"], self.raw["conventions"]
        self.w("## 2. NuSCR notation and execution semantics", "",
               "A NuSCR specification consists of a hierarchical **Function Overview Diagram (FOD)** describing the "
               "data flow between nodes, and one definition per node: a **Structured Decision Table (SDT)** for a "
               "function variable, a **Finite State Machine (FSM)** for a history variable, or a **Timed Transition "
               "System (TTS)** for a timed-history variable.", "")
        titles = {"execution": "Execution", "sdt": "SDT", "fsm": "FSM", "tts": "TTS",
                  "initialization": "Initialisation", "types": "Types", "ranges": "Range invariants"}
        for key, text in sem.items():
            self.w(f"**{titles.get(key, key)}.** {text}", "")
        self.w("### Conventions", "",
               table(["Prefix", "Meaning"], [[code(p), m] for p, m in conv["prefixes"].items()]), "",
               f"**Polarity.** {conv['polarity']}", "", f"**Time.** {conv['time_unit']}", "",
               table(["Unit", "Meaning"], [[code(u), m] for u, m in conv["units"].items()]), "",
               "### Types", "",
               table(["Type", "Values", "Description"],
                     [[code(n), ", ".join(f"{v} = {t.get('labels', {}).get(str(v), v)}" for v in t["values"])
                       if t.get("values") is not None else "real", t.get("description", "")]
                      for n, t in self.raw["types"].items()]), "")

    def section_3(self):
        bp = self.spec.modules.get("BP")
        n_fn = sum(1 for g in bp.groups if g.raw.get("logic_type")) if bp else 0
        self.w("## 3. System overview", "",
               self.raw["system"]["description"], "",
               "```mermaid", "flowchart LR")
        for inst in self.raw["system"]["instances"]:
            if inst["module"] == "BP":
                self.w(f"  IN_{inst['channel']}([\"Channel {inst['channel']} process inputs,<br/>operator module, "
                       f"CPC link\"]) --> {inst['name']}[\"{inst['name']}<br/>Bistable Processor\"]",
                       f"  {inst['name']} -->|\"trip + bypass status<br/>({n_fn} functions)\"| CP_A")
        self.w("  CP_A[\"CP_A<br/>Coincidence Processor<br/>(one per channel, identical)\"] -->|f_RT_Init| "
               "RT[(\"Reactor trip initiation<br/>(switchgear out of scope)\")]", "```", "")
        if bp:
            rows = []
            for g in bp.groups:
                if not g.raw.get("logic_type"):
                    continue
                x = g.name[2:]
                rows.append([code(g.name), g.raw["title"], code(g.raw["logic_type"]), g.raw["category"],
                             ", ".join(code(n) for n in sorted(self._group_external_inputs(bp, g))
                                       if n.startswith("f_") and not n.endswith(("_Ini", "_Reset", "_Error"))),
                             code(f"th_{x}_Trip")])
            self.w("### Trip functions", "",
                   "Trip functions are grouped into four logic categories: fixed set-point, variable set-point, "
                   "manual reset and digital trips.", "",
                   table(["Group", "Function", "NuSCR logic type", "Category", "Main inputs", "Trip output"], rows),
                   "")

    def section_4(self):
        self.w("## 4. System requirements", "",
               "Notional system-level requirements allocated to the NuSCR specification.  Each NuSCR node lists "
               f"the requirements it implements (section {7 + len(self.spec.modules)} gives the full matrix).", "",
               table(["ID", "Requirement"], [[f"**{r['id']}**", cell(r["text"])]
                                             for r in self.raw["requirements"]]), "")

    def section_5(self):
        self.w("## 5. Constants and setpoints", "",
               "> **All values are ILLUSTRATIVE placeholders** chosen only to make the specification concrete and "
               "self-consistent.  Replace them with values from the plant safety analysis and setpoint "
               "methodology.  `DERIVED` constants are computed from other constants.", "")
        by_cat = defaultdict(list)
        for c in self.raw["constants"]:
            by_cat[c.get("category", "other")].append(c)
        for cat in ("timing", "range", "setpoint", "hysteresis", "permissive", "other"):
            if cat not in by_cat:
                continue
            rows = []
            for c in by_cat[cat]:
                val = c.get("value") if "value" in c else f"{c['expr']} = {format_number(self.spec.constants[c['name']])}"
                rows.append([code(c["name"]), code(val), c.get("unit", ""), c["status"], cell(c["description"])])
            self.w(f"### Constants: {cat}", "", table(["Name", "Value", "Unit", "Status", "Description"], rows), "")
        self.w("### Constant assertions", "",
               "Relations between constants that the design relies on; evaluated by `nuscr_check.py`.", "",
               table(["ID", "Assertion", "Rationale", "Holds"],
                     [[a["id"], code(a["expr"]), cell(a["rationale"]),
                       "no" if any(f.where == f"assertion {a['id']}" for f in self.report.errors) else "yes"]
                      for a in self.raw["assertions"]]), "")

    # ------------------------------------------------------------------
    def _group_external_inputs(self, m, g):
        defined = {n.name for n in g.children}
        ext = set()
        for n in g.children:
            ext |= m.data_inputs(n.name) - defined
        return ext

    def module_section(self, num, m):
        self.w(f"## {num}. Module {m.name} - {m.title}", "", m.raw.get("description", ""), "")
        # interface
        rows = []
        for n in m.inputs:
            v = m.variables[n]
            rows.append([code(n), code(v["type"]), v.get("unit", ""), code(v.get("nominal", "")),
                         cell(v.get("source", "")), cell(v["description"])])
        self.w(f"### {num}.1 Inputs", "", table(["Input", "Type", "Unit", "Nominal (illustrative)", "Source",
                                                  "Description"], rows), "")
        rows = [[code(o), code(m.variables[o]["type"]), m.variables[o].get("unit", ""),
                 cell(m.variables[o]["description"])] for o in m.outputs]
        self.w(f"### {num}.2 Outputs", "", table(["Output", "Type", "Unit", "Description"], rows), "")
        # top-level FOD
        self.w(f"### {num}.3 Top-level FOD `{m.fod.get('name')}`", "", "```mermaid", "flowchart LR")
        owner = {n.name: g for g in m.groups for n in g.children}
        edges = set()
        for g in m.groups:
            self.w(f"  {g.name}[\"{g.no} {g.name}\"]")
            for n in g.children:
                for i in m.data_inputs(n.name):
                    if i in owner and owner[i] is not g:
                        edges.add((owner[i].name, g.name))
        for a, b in sorted(edges):
            self.w(f"  {a} --> {b}")
        self.w("```", "", "Module inputs are omitted from this diagram; they are shown on each group's FOD.", "",
               table(["No.", "Group", "Title", "Logic type", "Nodes", "Implements"],
                     [[g.no, code(g.name), g.raw.get("title", ""), code(g.raw.get("logic_type", "")),
                       len(g.children), ", ".join(g.raw.get("traces", []))] for g in m.groups]), "")
        # execution order
        chunks = [f"{i + 1}. `{v}` ({m.nodes[v].no})" for i, v in enumerate(m.execution_order)]
        self.w(f"### {num}.4 Execution order", "",
               "Topological order of the FOD data flow (dependencies first, ties broken by node number):", "",
               "<details><summary>Show all " + str(len(chunks)) + " nodes</summary>", "")
        self.w(*chunks)
        self.w("", "</details>", "")
        # proof obligations
        self.w(f"### {num}.5 Proof obligations", "",
               "Formulas proved valid by `tools/nuscr_check.py` for all inputs (constants substituted, proved range "
               "invariants assumed), and states proved to be left whenever the stated condition holds.", "")
        if m.obligations:
            self.w(table(["ID", "Formula", "Rationale"],
                         [[ob["id"], code(ob["formula"]), cell(ob.get("rationale", ""))] for ob, _ in m.obligations]),
                   "")
        exits = [(var, st, text) for var, d in m.definitions.items() for st, text, _ in d.must_exit]
        if exits:
            self.w(table(["Machine", "State", "Must be left when"],
                         [[code(var), st, code(text)] for var, st, text in exits]), "")
        forced = [(var, w, v) for var, d in m.definitions.items() for w, _, v, _ in d.forced_value]
        if forced:
            self.w("Forced values: whenever the condition holds, the variable has the value after the scan, "
                   "from every state (the fail-safe property of SYS-GEN-02).", "",
                   table(["Machine", "Condition", "Value"], [[code(var), code(w), code(v)] for var, w, v in forced]),
                   "")
        if not m.obligations and not exits and not forced:
            self.w("None.", "")
        # groups
        self.w(f"### {num}.6 Groups and node definitions", "")
        for g in m.groups:
            self.group_section(m, g)

    def group_section(self, m, g):
        self.w(f"#### {m.name}.{g.no} `{g.name}` - {g.raw.get('title', '')}", "", cell(g.raw.get("description", "")), "")
        if g.raw.get("logic_type"):
            self.w(f"NuSCR logic type: `{g.raw['logic_type']}` ({g.raw.get('category', '')}).  "
                   f"Implements: {', '.join(g.raw.get('traces', []))}.", "")
        defined = {n.name for n in g.children}
        self.w("```mermaid", "flowchart LR")
        ext = sorted(self._group_external_inputs(m, g))
        for x in ext:
            self.w(f"  x_{x}([\"{x}\"])")
        for n in g.children:
            out = " (out)" if n.name in m.outputs else ""
            self.w(f"  {n.name}[\"{n.no} {n.name}<br/>{n.type}{out}\"]")
        for n in g.children:
            for i in sorted(m.data_inputs(n.name)):
                src = i if i in defined else f"x_{i}"
                self.w(f"  {src} --> {n.name}")
        self.w("```", "",
               table(["No.", "Node", "Kind", "Inputs"],
                     [[n.no, code(n.name), n.type, ", ".join(code(i) for i in sorted(m.data_inputs(n.name)))]
                      for n in g.children]), "")
        for n in g.children:
            self.definition_section(m, n)

    def definition_section(self, m, n):
        d = m.definitions[n.name]
        v = m.variables[n.name]
        rng = f", range invariant `[{v['range'][0]}, {v['range'][1]}]`" if "range" in v else ""
        unit = f", unit {v['unit']}" if v.get("unit") else ""
        self.w(f"##### {m.name}.{n.no} `{n.name}` ({d.kind})", "",
               f"*{v['class'].replace('_', '-')} variable, type `{v['type']}`{unit}{rng}.*  "
               f"Implements: {', '.join(d.raw.get('traces', []))}.", "", cell(d.raw.get("description", "")), "")
        if d.kind == "SDT":
            header = [""] + [f"R{r.index}" for r in d.rules]
            rows = [["**Conditions**"] + [""] * len(d.rules)]
            for i, (text, _) in enumerate(d.conditions):
                rows.append([code(text)] + [r.cells[i] for r in d.rules])
            rows.append(["**Actions**"] + [""] * len(d.rules))
            for i, (text, _) in enumerate(d.actions):
                rows.append([code(f"{d.var} := {text}")] + ["O" if r.action == i else "" for r in d.rules])
            self.w(table(header, rows, ["---"] + [":-:"] * len(d.rules)), "")
        else:
            labels = {s: (f"{s} ({d.state_values[s][0]})" if d.state_values[s] is not None else s) for s in d.states}
            self.w("```mermaid", "stateDiagram-v2", f"  [*] --> {d.initial_state}")
            for t in d.transitions:
                timing = " (timed)" if t.timed else ""
                self.w(f"  {t.source} --> {t.target} : {t.id}{timing}")
            self.w("```", "",
                   f"States: {', '.join(labels[s] for s in d.states)}.  Initial state `{d.initial_state}`, "
                   f"initial value `{d.initial_value[0]}`." +
                   "".join(f"  Must leave `{st}` whenever `{cell(text)}` (proved)." for st, text, _ in d.must_exit) +
                   "".join(f"  Value is `{v}` after every scan in which `{cell(w)}` (proved)."
                           for w, _, v, _ in d.forced_value),
                   "",
                   table(["ID", "From", "To", "Timing", "Guard", "Action"],
                         [[t.id, t.source, t.target,
                           code(f"[{t.lower_text}, {t.upper_text}]") if t.timed else "",
                           code(t.guard_text), code(f"{d.var} := {t.action_text}")] for t in d.transitions]), "")

    # ------------------------------------------------------------------
    def system_section(self, num):
        sysd = self.raw["system"]
        self.w(f"## {num}. System configuration", "", sysd["description"], "",
               table(["Instance", "Module", "Channel", "Note"],
                     [[i["name"], i["module"], i["channel"], i.get("note", "")] for i in sysd["instances"]]), "",
               f"Evaluation order: {' -> '.join(sysd['evaluation_order'])}.  The {len(sysd['connections'])} "
               "connections follow the pattern below (full list in `data/connections.csv`); every other module "
               "input is an external input.", "",
               table(["Target (CP_A input)", "Source"],
                     [[code("CP_A.f_<c>_<X>_Trip"), code("BP_<c>.th_<X>_Trip")],
                      [code("CP_A.f_<c>_<X>_Byp"), code("BP_<c>.f_<X>_Byp_Sw")],
                      [code("CP_A.f_<c>_Link_Error"), "external (communication diagnostics)"]]),
               "", "with `<c>` in A, B, C, D and `<X>` the trip function identifier.", "")

    def trace_section(self, num):
        self.w(f"## {num}. Traceability", "",
               "Requirement to NuSCR node (module.variable, FOD node).  Requirements met by the structure of the "
               "specification rather than by an individual node are listed as allocations.", "")
        rows = []
        alloc = {r["id"]: r.get("allocated_to", []) for r in self.raw["requirements"]}
        for rid, nodes in self.trace().items():
            parts = [f"{code(v)} ({mod}.{no})" for mod, v, no in nodes] + [f"allocated: {cell(a)}" for a in alloc.get(rid, [])]
            rows.append([f"**{rid}**", ", ".join(parts) or "*(none)*"])
        self.w(table(["Requirement", "Implemented by"], rows), "")

    def trace(self):
        out = {r["id"]: [] for r in self.raw["requirements"]}
        for m in self.spec.modules.values():
            for var in sorted(m.definitions, key=lambda v: fod_key(m.nodes[v].no)):
                for rid in m.definitions[var].raw.get("traces", []):
                    out.setdefault(rid, []).append((m.name, f"{m.name}.{var}", m.nodes[var].no))
        return out

    def verification_section(self, num):
        st = self.report.stats
        self.w(f"## {num}. Verification status", "",
               "Static analysis by `tools/nuscr_check.py` at document generation time:", "",
               table(["Check", "Count"], [[k, v] for k, v in sorted(st.items())]), "",
               f"**Result: {len(self.report.errors)} error(s), {len(self.report.warnings)} warning(s).**", "")
        if self.report.findings:
            self.w(table(["Severity", "Where", "Finding"],
                         [[f.severity, cell(f.where), cell(f.message)] for f in self.report.findings]), "")
        self.w("Dynamic verification (`python -B -m unittest discover -s tests`): scenario tests for every trip-logic "
               "type, exhaustive comparison of the coincidence logic with an oracle written from SYS-CP-01..04 "
               "(4096 input combinations per function tested), randomised property tests P1-P11 with state-coverage "
               "checks, replay of the example scenarios, and fault-injection tests proving that the checker "
               "detects each defect class it claims to detect.", "",
               "These activities establish internal consistency of this synthetic specification only.  They are "
               "not independent V&V and do not establish fitness for any real plant.", "")

    def grammar_appendix(self):
        self.w("## Appendix A - Expression grammar", "", "```text",
               "expr   := or", "or     := and   ('||' and)*", "and    := not   ('&&' not)*",
               "not    := '!' not | cmp", "cmp    := sum   (('=' | '!=' | '<' | '<=' | '>' | '>=') sum)?",
               "sum    := prod  (('+' | '-') prod)*", "prod   := unary (('*' | '/') unary)*",
               "unary  := '-' unary | atom", "atom   := NUMBER | IDENT | 'true' | 'false' | '(' expr ')'",
               "```", "",
               "`=` is equality.  Actions are stored as the right-hand side of `:=`.  Guards must be boolean "
               "combinations of linear (in)equalities (products only with constants), which makes the checker's "
               "proofs exact.", "")


