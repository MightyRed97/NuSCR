def build_constants():
    consts = [dict(c, status="ILLUSTRATIVE") for c in GLOBAL_CONSTANTS]
    for s, sig in SIGNALS.items():
        consts.append(dict(name=f"k_{s}_Valid_Min", value=sig["vmin"], unit=sig["unit"], category="range",
                           status="ILLUSTRATIVE", description=f"Lower limit of the valid range of f_{s}."))
        consts.append(dict(name=f"k_{s}_Valid_Max", value=sig["vmax"], unit=sig["unit"], category="range",
                           status="ILLUSTRATIVE", description=f"Upper limit of the valid range of f_{s}."))
    for t in TRIPS:
        unit = SIGNALS[t["signal"]]["unit"] if "signal" in t else None
        for key, val in t["c"].items():
            u, cat, desc = _CONST_DOC[key]
            u = {"sig": unit, "sig/s": f"{unit}/s", "ms": "ms"}[u]
            consts.append(dict(name=f"k_{t['id']}_{key}", value=val, unit=u, category=cat, status="ILLUSTRATIVE",
                               description=f"{t['title']}: {desc}"))
        if "SP_Rate" in t["c"]:
            x = t["id"]
            consts.append(dict(name=f"k_{x}_SP_Step", expr=f"k_{x}_SP_Rate * k_Scan_Period / 1000", unit=unit,
                               category="setpoint", status="DERIVED",
                               description=f"{t['title']}: maximum setpoint change per scan."))
    return consts


