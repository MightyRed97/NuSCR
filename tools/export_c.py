def _reads(st):
    texts = [st["expr"]] if "expr" in st else [t for case in st["cases"] for t in case] + [st["else"]]
    return set().union(*(variables(parse(t)) for t in texts))


def block_code(name, b):
    """(declarations for rps_blocks.h, definitions for rps_blocks.c) of one design block."""
    if len(b["outputs"]) != 1:
        raise ExportError(f"block {name}: exactly one output expected")
    ins = [(p["name"], value_type(p["type"])) for p in b["inputs"] + b["params"]]
    out, out_t = b["outputs"][0]["name"], value_type(b["outputs"][0]["type"])
    state = {p["name"]: value_type(p["type"]) for p in b["state"]}
    locs = {p["name"]: value_type(p["type"]) for p in b["locals"]}
    types = dict(ins)
    types.update({out: out_t}, **state, **locs)
    tr = CTranslator(types, state)
    params = ([f"{name}_State *s"] if state else []) + [f"{C_TYPE[t]} {n}" for n, t in ins]
    proto = f"{C_TYPE[out_t]} {name}({', '.join(params)})"
    h = comment(b["description"])
    if state:
        h.append("typedef struct {")
        for p in b["state"]:
            h += comment(f"{p['description']} Initial value {p['init']}.", "    ")
            h.append(f"    {C_TYPE[state[p['name']]]} {p['name']};")
        h += [f"}} {name}_State;", "", f"void {name}_init({name}_State *s);"]
    h += [proto + ";", ""]
    c = []
    if state:
        c += [f"void {name}_init({name}_State *s)", "{"]
        c += [f"    s->{p['name']} = {literal(Fraction(str(p['init'])), state[p['name']])};" for p in b["state"]]
        c += ["}", ""]
    c += [proto, "{"]
    read_last = {v[5:] for st in b["body"] for v in _reads(st) if v.startswith("last_") and v[5:] in state}
    c += [f"    const {C_TYPE[t]} last_{n} = s->{n};" for n, t in state.items() if n in read_last]
    for st in b["body"]:
        v, target = st["set"], types[st["set"]]
        if "expr" in st:
            c.append(f"    const {C_TYPE[target]} {v} = {tr.value(parse(st['expr']), target)};")
            continue
        c.append(f"    const {C_TYPE[target]} {v} =")
        for g, e in st["cases"]:
            c.append(f"        {tr.bool(parse(g))} ? {tr.value(parse(e), target)} :")
        c.append(f"        {tr.value(parse(st['else']), target)};")
    c += [f"    s->{n} = {n};" for n in state]
    c += [f"    return {out};", "}", ""]
    return h, c


def blocks_files(design):
    h, c = [], []
    for name, b in design.raw["blocks"].items():
        bh, bc = block_code(name, b)
        h += bh
        c += bc
    return {"rps_blocks.h": header(design, "rps_blocks", "the function blocks of the design.",
                                   ["<stdbool.h>", "<stdint.h>"], h),
            "rps_blocks.c": source(design, "rps_blocks", "the function blocks of the design.",
                                   ['"rps_blocks.h"'], c)}


