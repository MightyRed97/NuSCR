def threshold(x, sp, hys, rising):
    """(condition, negated condition, reset condition, negated reset condition) for a rising/falling comparison."""
    if rising:
        return f"{x} >= {sp}", f"{x} < {sp}", f"{x} < {sp} - {hys}", f"{x} >= {sp} - {hys}"
    return f"{x} <= {sp}", f"{x} > {sp}", f"{x} > {sp} + {hys}", f"{x} <= {sp} + {hys}"


def trip_machine(mb, g, x, which, err, ok, cond, ncond, reset, nreset, byp, traces, what):
    """Standard trip / pre-trip TTS (the NuSCR th_X_Trip pattern, with fail-safe initialisation).

    The process condition is evaluated only in error-free scans.  States:
      NORMAL, WAITING                 output 1; WAITING times the persistence of the condition.
      <WORD>_BY_LOGIC                 process trip (condition persisted for the delay); released by 'release'.
      <WORD>_BY_ERROR                 error trip, not preceded by a process trip.
      <WORD>_PENDING                  error cleared with the condition present: output held at 0 while its
                                      persistence is confirmed; becomes a process trip after the delay.
      <WORD>_BY_ERROR_LATCHED         error during a process trip: when the error clears the process trip is
                                      resumed unless 'release' holds, so hysteresis is kept across errors."""
    var = f"th_{x}_{which}"
    word = which.upper()
    delay = f"k_{x}_{which}_Delay"
    logic_st, err_st = f"{word}_BY_LOGIC", f"{word}_BY_ERROR"
    pend_st, latch_st = f"{word}_PENDING", f"{word}_BY_ERROR_LATCHED"
    if byp:
        arm = f"{ok} && {byp} = 0 && {cond}"
        clear = f"{ok} && ({byp} = 1 || {ncond})"
        release = f"{ok} && ({byp} = 1 || {reset})"
        hold = f"{ok} && {byp} = 0 && {nreset}"
    else:
        arm = f"{ok} && {cond}"
        clear = f"{ok} && {ncond}"
        release = f"{ok} && {reset}"
        hold = f"{ok} && {nreset}"
    desc = (f"{what}: goes to {word} after the {which.lower()} condition has persisted for {delay} in error-free "
            f"scans (NORMAL -> WAITING -> {logic_st}); goes to {word} immediately on an error; resets when "
            f"'{reset}'" + (f" or when the operating bypass {byp} is active" if byp else "") +
            f".  When an error clears with the condition present, the output stays at {word} in {pend_st} until "
            f"the condition has persisted for {delay} ({logic_st}) or clears (NORMAL).  An error during a process "
            f"trip is held in {latch_st}, so the reset condition still applies when the error clears.  Starts in "
            f"the fail-safe state {err_st}.")
    g.machine("TTS", var, desc, traces,
              [("NORMAL", "1"), ("WAITING", "1"), (logic_st, "0"), (err_st, "0"), (pend_st, "0"), (latch_st, "0")],
              err_st, "0",
              [("N1", "NORMAL", err_st, err, "0"),
               ("N2", "NORMAL", "WAITING", arm, "1"),
               ("W1", "WAITING", err_st, err, "0"),
               ("W2", "WAITING", "NORMAL", clear, "1"),
               ("W3", "WAITING", logic_st, arm, "0", (delay, delay)),
               ("L1", logic_st, latch_st, err, "0"),
               ("L2", logic_st, "NORMAL", release, "1"),
               ("E1", err_st, pend_st, arm, "0"),
               ("E2", err_st, "NORMAL", clear, "1"),
               ("P1", pend_st, err_st, err, "0"),
               ("P2", pend_st, "NORMAL", clear, "1"),
               ("P3", pend_st, logic_st, arm, "0", (delay, delay)),
               ("H1", latch_st, logic_st, hold, "0"),
               ("H2", latch_st, "NORMAL", release, "1")],
              must_exit=[(err_st, ok), (latch_st, ok)],
              forced_value=[(err, "0")])
    mb.obligation(f"PO-{x}-{word}-HYS", f"!(({cond}) && ({reset}))",
                  f"{var}: the reset condition must exclude the {which.lower()} condition (positive hysteresis), "
                  f"otherwise the output could chatter between {logic_st} and WAITING.")


def pulse_machine(g, var, pb, traces, what):
    """Edge detector: PULSE (1) for exactly one scan per press of pushbutton `pb`.  Starts in HELD, so that a
    button held or stuck at power-up is ignored until it has been seen released."""
    g.machine("FSM", var, f"Edge detector for {pb} ({what}): PULSE (1) for exactly one scan per press.  Starts "
              "in HELD so that a button held (or stuck) at start-up is ignored until released.", traces,
              [("ARMED", "0"), ("FIRED", "1"), ("HELD", "0")], "HELD", "0",
              [("T1", "ARMED", "FIRED", f"{pb} = 1", "1"),
               ("T2", "FIRED", "HELD", f"{pb} = 1", "0"),
               ("T3", "FIRED", "ARMED", f"{pb} = 0", "0"),
               ("T4", "HELD", "ARMED", f"{pb} = 0", "0")])


def ob_machine(g, x, perm, pulse, traces, title):
    g.machine("FSM", f"h_{x}_OB_Sta",
              f"{title} operating-bypass status: established by an operator initiation (a press of f_{x}_OB_Ini, "
              f"i.e. the pulse {pulse}) made while the permissive {perm} is present; a held or stuck pushbutton "
              f"does not establish the bypass.  Removed automatically as soon as the permissive is lost.  Removed "
              f"at start-up.",
              traces, [("NO_OB", "0"), ("OB", "1")], "NO_OB", "0",
              [("T1", "NO_OB", "OB", f"{perm} = 1 && {pulse} = 1", "1"),
               ("T2", "OB", "NO_OB", f"{perm} = 0", "0")])


