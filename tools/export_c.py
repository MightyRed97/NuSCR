def system_files(design):
    spec = design.spec
    sysd = spec.system
    insts = sysd["instances"]
    module = {i["name"]: i["module"] for i in insts}
    links = {}
    for con in sysd["connections"]:
        ti, tv = con["to"].split(".", 1)
        si, sv = con["from"].split(".", 1)
        links.setdefault(ti, []).append((tv, si, sv))
    h = comment(sysd["description"])
    h.append("")
    for what, suffix in (("Inputs of every instance, as the caller sets them.  RPS_System_step copies the inputs of "
                          "an instance that connections drive and sets the driven ones in the copy in every scan, so "
                          "values set here for a driven input are not used.", "Inputs"),
                         ("Every computed signal of every instance.", "Signals"),
                         ("State of every instance.", "State")):
        h += comment(what) + ["typedef struct {"]
        h += [f"    RPS_{module[i['name']]}_{suffix} {i['name']};" for i in insts]
        h += [f"}} RPS_System_{suffix};", ""]
    h += comment("Power-up of every instance.") + ["void RPS_System_init(RPS_System_State *st);", ""]
    h += comment("Nominal inputs of every instance.")
    h += ["void RPS_System_nominal_inputs(RPS_System_Inputs *in);", ""]
    h += comment(f"One scan of every instance in the evaluation order {' -> '.join(sysd['evaluation_order'])}; "
                 "connections are same-scan transfers.")
    h += ["void RPS_System_step(RPS_System_State *st, const RPS_System_Inputs *in, RPS_System_Signals *out);", ""]
    c = ["void RPS_System_init(RPS_System_State *st)", "{"]
    c += [f"    RPS_{module[i['name']]}_init(&st->{i['name']});" for i in insts]
    c += ["}", "", "void RPS_System_nominal_inputs(RPS_System_Inputs *in)", "{"]
    c += [f"    RPS_{module[i['name']]}_nominal_inputs(&in->{i['name']});" for i in insts]
    c += ["}", "", "void RPS_System_step(RPS_System_State *st, const RPS_System_Inputs *in, RPS_System_Signals *out)",
          "{"]
    c += [f"    RPS_{module[n]}_Inputs {n}_in = in->{n};" for n in sysd["evaluation_order"] if n in links]
    for n in sysd["evaluation_order"]:
        m = module[n]
        if n in links:
            c.append("")
            c += comment(f"connections into {n}", "    ")
            for tv, si, sv in links[n]:
                src = spec.modules[module[si]]
                where = "in" if sv in src.inputs else "out"
                c.append(f"    {n}_in.{tv} = {where}->{si}.{sv};")
            c.append(f"    RPS_{m}_step(&st->{n}, &{n}_in, &out->{n});")
        else:
            c.append(f"    RPS_{m}_step(&st->{n}, &in->{n}, &out->{n});")
    c += ["}", ""]
    mods = sorted(set(module.values()))
    purpose = "the four-channel system: every BP and the CP, with their connections."
    return {"rps_system.h": header(design, "rps_system", purpose, [f'"rps_{m.lower()}.h"' for m in mods], h),
            "rps_system.c": source(design, "rps_system", purpose, ['"rps_system.h"'], c)}


def constants_files(design, derived):
    spec = design.spec
    used, delays = used_constants(design)
    used = set(used) | {"k_Scan_Period"}
    h = comment("Constants of the requirements specification that the design uses (unit in the comment).")
    c = []
    for k in sorted(used):
        unit = spec.const_meta[k].get("unit", "")
        h.append(f"extern const double {k};" + (f"  /* {unit} */" if unit else ""))
        c.append(f"const double {k} = {literal(spec.constants[k], 'float64')};")
    h += ["", *comment("Persistence delays in scans (delay constant / k_Scan_Period).")]
    c.append("")
    for name, (value, expr) in sorted(delays.items()):
        h.append(f"extern const int32_t {name};  /* = {expr} */")
        c.append(f"const int32_t {name} = {literal(value, 'int32')};")
    h += ["", *comment("Thresholds made only of constants, evaluated exactly at generation time and rounded once.")]
    c.append("")
    for name, (value, expr) in sorted(derived.items()):
        h.append(f"extern const double {name};  /* = {expr} */")
        c.append(f"const double {name} = {literal(value, 'float64')};")
    h.append("")
    c.append("")
    purpose = "constants of the design."
    return {"rps_constants.h": header(design, "rps_constants", purpose, ["<stdint.h>"], h),
            "rps_constants.c": source(design, "rps_constants", purpose, ['"rps_constants.h"'], c)}


def meta_files(design):
    spec = design.spec
    sysd = spec.system
    h = comment("Value types of the inputs and signals.")
    h += ["typedef enum { RPS_BOOL = 0, RPS_INT32 = 1, RPS_REAL = 2 } RPS_Type;", ""]
    h += comment("One member of an Inputs or Signals structure.  A flag's labels name its values (for a trip "
                 "signal: 0 TRIP, 1 NORMAL); they are NULL for other types.")
    h += ["typedef struct {", "    const char *name;", "    RPS_Type type;", "    size_t offset;",
          "    const char *unit;", "    const char *label0;", "    const char *label1;", "} RPS_Field;", ""]
    h += comment("A module: its fields and functions, for tools that handle BP and CP alike.")
    h += ["typedef struct {", "    const char *name;", "    const RPS_Field *inputs;", "    size_t n_inputs;",
          "    const RPS_Field *signals;", "    size_t n_signals;", "    size_t state_size;", "    size_t inputs_size;",
          "    size_t signals_size;", "    void (*init)(void *state);", "    void (*nominal_inputs)(void *inputs);",
          "    void (*step)(void *state, const void *inputs, void *signals);", "} RPS_Module;", ""]
    h += comment("An instance of the system: where its inputs and signals are in RPS_System_Inputs and "
                 "RPS_System_Signals.")
    h += ["typedef struct {", "    const char *name;", "    const RPS_Module *module;", "    size_t inputs_offset;",
          "    size_t signals_offset;", "} RPS_Instance;", ""]
    c = []
    mods = [m for m in ("BP", "CP") if m in design.modules]
    for m in mods:
        req = spec.modules[m]
        vt = {n: signal_type(spec.types, v["type"]) for n, v in req.variables.items()}
        for what, names, struct in (("INPUTS", req.inputs, "Inputs"), ("SIGNALS", design_signals(design, m), "Signals")):
            c.append(f"static const RPS_Field {m}_{what}[] = {{")
            for n in names:
                v = req.variables[n]
                labels = spec.types[v["type"]].get("labels") if vt[n] == "bool" else None
                l0, l1 = (f'"{labels["0"]}"', f'"{labels["1"]}"') if labels else ("NULL", "NULL")
                c.append(f'    {{"{n}", {META_TYPE[vt[n]]}, offsetof(RPS_{m}_{struct}, {n}), "{v.get("unit", "")}", '
                         f"{l0}, {l1}}},")
            c += ["};", ""]
        lo = m.lower()
        c += [f"static void {lo}_init(void *state)", "{", f"    RPS_{m}_init((RPS_{m}_State *)state);", "}", "",
              f"static void {lo}_nominal_inputs(void *inputs)", "{",
              f"    RPS_{m}_nominal_inputs((RPS_{m}_Inputs *)inputs);", "}", "",
              f"static void {lo}_step(void *state, const void *inputs, void *signals)", "{",
              f"    RPS_{m}_step((RPS_{m}_State *)state, (const RPS_{m}_Inputs *)inputs, (RPS_{m}_Signals *)signals);",
              "}", "",
              f"const RPS_Module RPS_MODULE_{m} = {{",
              f'    "{m}", {m}_INPUTS, sizeof {m}_INPUTS / sizeof {m}_INPUTS[0],',
              f"    {m}_SIGNALS, sizeof {m}_SIGNALS / sizeof {m}_SIGNALS[0],",
              f"    sizeof(RPS_{m}_State), sizeof(RPS_{m}_Inputs), sizeof(RPS_{m}_Signals),",
              f"    {lo}_init, {lo}_nominal_inputs, {lo}_step", "};", ""]
        h.append(f"extern const RPS_Module RPS_MODULE_{m};")
    c.append("const RPS_Instance RPS_SYSTEM_INSTANCES[] = {")
    for i in sysd["instances"]:
        n = i["name"]
        c.append(f'    {{"{n}", &RPS_MODULE_{i["module"]}, offsetof(RPS_System_Inputs, {n}), '
                 f"offsetof(RPS_System_Signals, {n})}},")
    c += ["};", "", f"const size_t RPS_SYSTEM_N_INSTANCES = sizeof RPS_SYSTEM_INSTANCES / sizeof RPS_SYSTEM_INSTANCES[0];",
          "", "const RPS_Connection RPS_SYSTEM_CONNECTIONS[] = {"]
    c += [f'    {{"{con["to"]}", "{con["from"]}"}},' for con in sysd["connections"]]
    c += ["};", "",
          "const size_t RPS_SYSTEM_N_CONNECTIONS = sizeof RPS_SYSTEM_CONNECTIONS / sizeof RPS_SYSTEM_CONNECTIONS[0];", ""]
    h += ["extern const RPS_Instance RPS_SYSTEM_INSTANCES[];", "extern const size_t RPS_SYSTEM_N_INSTANCES;", ""]
    h += comment("A connection of the system: RPS_System_step sets input `to` (INSTANCE.input) to `from` (INSTANCE.signal "
                 "or INSTANCE.input) in every scan.  RPS_System_Inputs keeps what was set there, not the value "
                 "delivered.")
    h += ["typedef struct {", "    const char *to;", "    const char *from;", "} RPS_Connection;", "",
          "extern const RPS_Connection RPS_SYSTEM_CONNECTIONS[];", "extern const size_t RPS_SYSTEM_N_CONNECTIONS;", ""]
    purpose = "names, types and offsets of every input and signal."
    return {"rps_meta.h": header(design, "rps_meta", purpose, ["<stddef.h>"], h),
            "rps_meta.c": source(design, "rps_meta", purpose, ['"rps_meta.h"', '"rps_system.h"'], c)}


def generate(design):
    """{file name: text} of every generated source file."""
    derived, files = {}, {}
    files.update(blocks_files(design))
    for m in ("BP", "CP"):                       # same order as the SCADE export, so the derived constants match
        files.update(module_files(design, m, derived))
    files.update(system_files(design))
    files.update(constants_files(design, derived))
    files.update(meta_files(design))
    return files


def main():
    design = load_design()
    C_SOURCE_DIR.mkdir(parents=True, exist_ok=True)
    files = generate(design)
    for name, text in files.items():
        (C_SOURCE_DIR / name).write_text(text, encoding="utf-8", newline="\n")
    stale = sorted(p.name for p in C_SOURCE_DIR.glob("rps_*.[ch]") if p.name not in files)
    for name in stale:
        (C_SOURCE_DIR / name).unlink()
    lines = sum(t.count("\n") for t in files.values())
    print(f"wrote {len(files)} files ({lines} lines) in {C_SOURCE_DIR}" + (f"; removed {stale}" if stale else ""))


if __name__ == "__main__":
    main()
